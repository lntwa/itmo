WITH МИН_ОЦЕНКА_1101 AS (
    SELECT MIN(CAST(Н_ВЕДОМОСТИ.ОЦЕНКА AS INT)) AS МИН_ОЦЕНКА
    FROM Н_ВЕДОМОСТИ
    INNER JOIN Н_ЛЮДИ ON Н_ВЕДОМОСТИ.ЧЛВК_ИД = Н_ЛЮДИ.ИД
    INNER JOIN Н_ОБУЧЕНИЯ ON Н_ЛЮДИ.ИД = Н_ОБУЧЕНИЯ.ЧЛВК_ИД
    INNER JOIN Н_УЧЕНИКИ ON Н_ОБУЧЕНИЯ.ЧЛВК_ИД = Н_УЧЕНИКИ.ИД
    WHERE Н_УЧЕНИКИ.ГРУППА = '1101'
    AND ОЦЕНКА IN ('2', '3', '4', '5')
),

СР_ОЦЕНКА_4100 AS (
    SELECT Н_ЛЮДИ.ИД AS СТУДЕНТ_ИД, AVG(CAST(Н_ВЕДОМОСТИ.ОЦЕНКА AS INT)) AS СР_ОЦЕНКА
    FROM Н_ВЕДОМОСТИ
    INNER JOIN Н_ЛЮДИ ON Н_ВЕДОМОСТИ.ЧЛВК_ИД = Н_ЛЮДИ.ИД
    INNER JOIN Н_ОБУЧЕНИЯ ON Н_ЛЮДИ.ИД = Н_ОБУЧЕНИЯ.ЧЛВК_ИД
    INNER JOIN Н_УЧЕНИКИ ON Н_ОБУЧЕНИЯ.ЧЛВК_ИД = Н_УЧЕНИКИ.ИД
    WHERE Н_УЧЕНИКИ.ГРУППА = '4100'
    A
    GROUP BY Н_ЛЮДИ.ИД
)


    SELECT Н_ЛЮДИ.ИД AS СТУДЕНТ_ИД, AVG(CAST(Н_ВЕДОМОСТИ.ОЦЕНКА AS INT)) AS СР_ОЦЕНКА
    FROM Н_ВЕДОМОСТИ
    INNER JOIN Н_ЛЮДИ ON Н_ВЕДОМОСТИ.ЧЛВК_ИД = Н_ЛЮДИ.ИД
    INNER JOIN Н_ОБУЧЕНИЯ ON Н_ЛЮДИ.ИД = Н_ОБУЧЕНИЯ.ЧЛВК_ИД
