        INNER JOIN Н_УЧЕНИКИ ON Н_ОБУЧЕНИЯ.ЧЛВК_ИД = Н_УЧЕНИКИ.ИД
        WHERE Н_УЧЕНИКИ.ГРУППА = '3101'
        AND ОЦЕНКА IN ('2', '3', '4', '5')
    );


WITH МИН_ОЦЕНКА_1101 AS (
    SELECT MIN(CAST(Н_ВЕДОМОСТИ.ОЦЕНКА AS INT)) AS МИН_ОЦЕНКА
    FROM Н_ВЕДОМОСТИ
